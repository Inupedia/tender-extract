"""
增强版正则表达式模式库

成熟方案核心思想：
1. 分层置信度：精确模式（0.95）> 宽松模式（0.8）> 启发式（0.6）
2. 多变体覆盖：同一字段的不同表述方式
3. 中文特有模式：大写金额、中文日期、统一社会信用代码等
4. 表格感知：能从 Markdown 表格中提取数据
"""
import re
from typing import List, Tuple
from dataclasses import dataclass


@dataclass
class PatternDef:
    """模式定义"""
    pattern: str
    confidence: float
    description: str
    flags: int = re.IGNORECASE | re.MULTILINE


