def compile_patterns(
    pattern_defs: List[PatternDef],
) -> List[Tuple[re.Pattern, float, str]]:
    """编译模式列表"""
    compiled = []
    for pdef in pattern_defs:
        try:
            compiled.append((
                re.compile(pdef.pattern, pdef.flags),
                pdef.confidence,
                pdef.description
            ))
        except re.error as e:
            import logging
            logging.getLogger(__name__).warning(
                f"正则编译失败: {pdef.description} - {e}"
            )
    return compiled
